import assert from "node:assert/strict";
import { createHash, randomUUID } from "node:crypto";
import { execFileSync } from "node:child_process";
import { mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { verifyInstallation } from "./installation-preflight.mjs";

const HASH = /^[a-f0-9]{64}$/;
const COMMIT = /^[a-f0-9]{40}$/;
const IMAGE_ID = /^sha256:[a-f0-9]{64}$/;
const REPO = "devonalanakins/mizvo";
const SOURCE = "https://github.com/" + REPO;
const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");

function requireValid(condition, message) {
  if (!condition) throw new Error(message);
}

export function parsePinnedBase(dockerfile) {
  const from = dockerfile
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter((line) => /^FROM\s+/i.test(line));
  requireValid(from.length === 2, "Expected exactly two OCI image stages.");
  const bases = from.map((line) => {
    const matched = line.match(
      /^FROM (node:24-bookworm-slim@sha256:([a-f0-9]{64})) AS (build|runtime)$/,
    );
    requireValid(matched, "Node OCI base must use an immutable SHA-256 index digest.");
    return {
      reference: matched[1],
      digest: matched[2],
      stage: matched[3],
    };
  });
  requireValid(
    bases[0].stage === "build" && bases[1].stage === "runtime",
    "OCI stage order must be build, then runtime.",
  );
  requireValid(
    bases[0].reference === bases[1].reference,
    "OCI stages must use the same approved base index digest.",
  );
  return bases[0];
}

function command(program, args) {
  return execFileSync(program, args, {
    encoding: "utf8",
    timeout: 90_000,
    maxBuffer: 2 * 1024 * 1024,
    stdio: ["ignore", "pipe", "pipe"],
  }).trim();
}

export async function verifyOciImage(image) {
  requireValid(
    typeof image === "string" &&
      /^mizvo-ci-stage-[A-Za-z0-9_.-]+$/.test(image) &&
      image.length <= 128,
    "Expected an isolated CI image name.",
  );
  requireValid(
    process.env.GITHUB_REPOSITORY === REPO,
    "OCI evidence may only be generated by Mizvo's own CI repository.",
  );

  const [source, manifestRaw, dockerfile] = await Promise.all([
    readFile("package-lock.json"),
    readFile("build-proof.json"),
    readFile("Dockerfile", "utf8"),
  ]);
  const manifest = JSON.parse(manifestRaw.toString("utf8"));
  const checkoutCommit = command("git", ["rev-parse", "HEAD"]);
  const checkoutTree = command("git", ["rev-parse", "HEAD^{tree}"]);
  const base = parsePinnedBase(dockerfile);
  requireValid(
    COMMIT.test(checkoutCommit) && COMMIT.test(checkoutTree),
    "Invalid checked-out Git identity.",
  );
  requireValid(
    !process.env.GITHUB_SHA || process.env.GITHUB_SHA === checkoutCommit,
    "GitHub CI SHA differs from checked-out source.",
  );
  requireValid(
    manifest.source?.repository === REPO &&
      manifest.source?.checkout_commit === checkoutCommit &&
      manifest.source?.checkout_tree === checkoutTree &&
      manifest.source?.lockfile_sha256 === sha256(source),
    "OCI source and lockfile are not the compiled manifest source.",
  );
  const inspected = JSON.parse(command("docker", ["image", "inspect", image]));
  requireValid(
    Array.isArray(inspected) && inspected.length === 1,
    "Expected one local container image.",
  );
  const entry = inspected[0];
  requireValid(IMAGE_ID.test(entry.Id), "Invalid local OCI image ID.");
  requireValid(
    entry.Os === "linux" && entry.Config?.User === "node",
    "Image must be Linux and run as non-root Node user.",
  );
  const labels = entry.Config.Labels ?? {};
  requireValid(
    labels["org.opencontainers.image.source"] === SOURCE &&
      labels["org.opencontainers.image.revision"] === checkoutCommit &&
      labels["org.opencontainers.image.licenses"] === "AGPL-3.0-only" &&
      labels["org.mizvo.source.tree"] === checkoutTree,
    "Local image labels disagree with trusted CI checkout.",
  );

  // An image's local config/content ID is NOT a published registry manifest
  // digest, and the reference from Dockerfile is only a pinned base digest.
  const work = await mkdtemp(join(tmpdir(), "mizvo-oci-image-proof-"));
  const container = "mizvo-oci-extract-" + randomUUID();
  let created = false;
  try {
    const extracted = join(work, "dist");
    await mkdir(extracted, { mode: 0o700 });
    command("docker", [
      "create",
      "--name",
      container,
      "--entrypoint",
      "node",
      image,
      "--version",
    ]);
    created = true;
    command("docker", ["cp", container + ":/app/dist/.", extracted]);
    const install = await verifyInstallation({
      distribution: extracted,
      manifest: resolve("build-proof.json"),
      trustedManifestSha256: sha256(manifestRaw),
      expectedCommit: checkoutCommit,
      expectedTree: checkoutTree,
      expectedRepository: REPO,
    });
    assert(install.passed && install.files_verified === manifest.files.length);

    const receipt = {
      schema: "mizvo.oci-image-proof.v1",
      observed_at: new Date().toISOString(),
      scope: "CI-local OCI image ID and verified embedded distribution; not a registry release.",
      source: {
        repository: REPO,
        checkout_commit: checkoutCommit,
        checkout_tree: checkoutTree,
        lockfile_sha256: sha256(source),
      },
      immutable_base_index_reference: base.reference,
      immutable_base_index_digest: base.digest,
      local_image_id: entry.Id,
      image_architecture: entry.Architecture,
      application_user: entry.Config.User,
      compiled_manifest_sha256: sha256(manifestRaw),
      compiled_files_verified: install.files_verified,
      embedded_dist_matches_ci_manifest: true,
      image_checkout_labels_match: true,
      runtime_container_execution_verified_here: false,
      independently_trusted_manifest_digest: false,
      registry_manifest_digest_verified: false,
      signed_attestation_verified: false,
      external_deployment_verified: false,
      limitations: [
        "The same CI job supplied the manifest and image label trust anchors.",
        "Local Docker image IDs are not externally published registry manifest digests.",
        "The image base is pinned to a registry index digest, but this check is not an independent supply-chain signature.",
        "The image was inspected on disk; which bytes execute on a real customer host is not attested.",
      ],
    };
    await mkdir(resolve("docs/evidence"), { recursive: true });
    await writeFile(
      "docs/evidence/oci-image-proof.json",
      JSON.stringify(receipt, null, 2) + "\n",
      { flag: "w", mode: 0o600 },
    );
    console.log(
      "PASS: pinned OCI base, source labels and " +
        install.files_verified +
        " embedded compiled files match CI manifest.",
    );
  } finally {
    if (created) {
      try {
        command("docker", ["rm", "-f", container]);
      } catch {
        // Preserve original check failure; Docker cleanup can fail separately.
      }
    }
    await rm(work, { recursive: true, force: true });
  }
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  if (process.argv.length !== 3) {
    console.error("Usage: node scripts/oci-image-proof.mjs <ephemeral-ci-image>");
    process.exitCode = 2;
  } else {
    try {
      await verifyOciImage(process.argv[2]);
    } catch (error) {
      console.error("FAIL: OCI image integrity: " + error.message);
      process.exitCode = 1;
    }
  }
}
